-- Additive accounting preferences. Existing financial records and allocations are untouched.
ALTER TABLE credit_cards
  ADD COLUMN IF NOT EXISTS budget_attribution TEXT NOT NULL DEFAULT 'statement'
  CHECK (budget_attribution IN ('statement', 'due'));

INSERT INTO app_settings(setting_key, setting_value)
VALUES
  ('outstanding_display_mode', 'both'),
  ('payment_allocation_policy', 'generated_by_payment_date')
ON CONFLICT (setting_key) DO NOTHING;

-- Keep a reversible snapshot whenever the user explicitly changes allocation policy.
CREATE TABLE IF NOT EXISTS payment_allocation_rebuild_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  previous_policy TEXT NOT NULL,
  new_policy TEXT NOT NULL,
  allocations_before JSONB NOT NULL,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
