function monthDay(y,m,d){const last=new Date(Date.UTC(y,m,0)).getUTCDate();return `${y}-${String(m).padStart(2,'0')}-${String(Math.min(d,last)).padStart(2,'0')}`;}
function shiftMonth(y,m,delta){const d=new Date(Date.UTC(y,m-1+delta,1));return [d.getUTCFullYear(),d.getUTCMonth()+1];}
/** Canonical card cycle rule, using settlement dates and month-end day clamping. */
export function cycleFor(card,date){const [Y,M]=date.slice(0,10).split('-').map(Number),day=Number(card.billing_day);let y=Y,m=M,start,end;if(card.billing_rule==='end'){end=monthDay(y,m,day);if(date.slice(0,10)>end){[y,m]=shiftMonth(y,m,1);end=monthDay(y,m,day);}const [py,pm]=shiftMonth(y,m,-1);start=new Date(`${monthDay(py,pm,day)}T00:00:00Z`);start.setUTCDate(start.getUTCDate()+1);start=start.toISOString().slice(0,10);}else{start=monthDay(y,m,day);if(date.slice(0,10)<start){[y,m]=shiftMonth(y,m,-1);start=monthDay(y,m,day);}const [ny,nm]=shiftMonth(y,m,1);const next=new Date(`${monthDay(ny,nm,day)}T00:00:00Z`);next.setUTCDate(next.getUTCDate()-1);end=next.toISOString().slice(0,10);}const due=new Date(`${end}T00:00:00Z`);due.setUTCDate(due.getUTCDate()+Math.max(0,Number(card.due_days)||0));const statement=new Date(`${end}T00:00:00Z`);statement.setUTCDate(statement.getUTCDate()+1);
return {start,end,statement_date:statement.toISOString().slice(0,10),due_date:due.toISOString().slice(0,10)};}

/**
 * Reconstruct generated/due dates for a persisted statement only when its stored
 * cycle boundaries still match the card's current billing rule. This lets the
 * API repair stale statement_date/due_date metadata without reinterpreting
 * historical cycles after a user changes a card's billing configuration.
 */
export function datesForStoredCycle(card, cycleStart, cycleEnd) {
  const cycle = cycleFor(card, String(cycleStart).slice(0, 10));
  if (cycle.start !== String(cycleStart).slice(0, 10) || cycle.end !== String(cycleEnd).slice(0, 10)) {
    return null;
  }
  return { statement_date: cycle.statement_date, due_date: cycle.due_date };
}

/** True when the statement was generated in the selected reporting month.
 * Monthly billed totals are attributed by statement_date, not cycle_start or due_date.
 */
export function isStatementGeneratedInMonth(statementDate, selectedMonth) {
  return String(statementDate).slice(0, 7) === selectedMonth;
}

/** True when a cycle starts in the selected month. */
export function isCurrentMonthCycle(cycle, selectedMonth) {
  return cycle.start.slice(0, 7) === selectedMonth;
}

/**
 * Calculate statement-ledger totals for the dashboard.
 * Billed is the immutable face value of statements generated in selectedMonth.
 * Outstanding is the remaining balance of every statement generated by today,
 * including older unpaid statements carried forward from previous months.
 */
export function calculateStatementTotals(statements, selectedMonth, today) {
  let billedMinor = 0;
  let outstandingMinor = 0;

  for (const statement of statements) {
    const statementDate = String(statement.statement_date || '').slice(0, 10);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(statementDate) || statementDate > today) continue;

    const bill = Number(statement.bill_amount_minor ?? statement.amount_minor ?? 0);
    const outstanding = Number(statement.outstanding_minor ?? 0);
    if (!Number.isSafeInteger(bill) || bill < 0 || !Number.isSafeInteger(outstanding) || outstanding < 0) {
      throw new TypeError(`Invalid statement amounts for statement ${statement.id ?? 'unknown'}.`);
    }

    if (isStatementGeneratedInMonth(statementDate, selectedMonth)) billedMinor += bill;
    outstandingMinor += outstanding;
  }

  return { billedMinor, outstandingMinor };
}

/** Select the month used for budget attribution without changing the canonical cycle. */
export function budgetAttributionDate(cycle, card) {
  return card?.budget_attribution === 'due' ? cycle.due_date : cycle.statement_date;
}

export function isBudgetAttributedToMonth(cycle, card, selectedMonth) {
  return String(budgetAttributionDate(cycle, card)).slice(0, 7) === selectedMonth;
}
